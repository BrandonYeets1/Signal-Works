    private MunicipalGlyphs() {}

    private static void put(char character, String... rows) {
        int[] encoded = new int[7];
        for (int row = 0; row < 7; row++) {
            encoded[row] = Integer.parseInt(rows[row], 2);
        }
        GLYPHS.put(character, encoded);
    }

    static int row(char character, int row) {
        int[] glyph = GLYPHS.get(character);
        if (glyph == null && Character.isLowerCase(character)) {
            glyph = GLYPHS.get(Character.toUpperCase(character));
        }
        if (glyph == null) {
            glyph = GLYPHS.get('?');
        }
        return glyph[row];
    }

    static int advance(char character) {
        return character == ' ' ? 4 : 6;
    }
